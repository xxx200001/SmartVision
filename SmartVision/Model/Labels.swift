    // MARK: - 翻译逻辑

    /// 取标签中的第一个同义词（ImageNet 标签常为 "a, b, c" 同义词串）
    static func firstSynonym(of identifier: String) -> String {
        identifier.components(separatedBy: ",")
            .first?
            .trimmingCharacters(in: .whitespacesAndNewlines)
            .lowercased() ?? identifier.lowercased()
    }

    /// 翻译：先整串精确匹配，再按第一个同义词匹配，均未命中则回退英文
    static func translate(_ identifier: String) -> String {
        let full = identifier.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        if let zh = dictionary[full] { return zh }
        let first = firstSynonym(of: identifier)
        if let zh = dictionary[first] { return zh }
        return first
    }

    /// 展示名：中文（英文原文），未收录时仅显示英文
    static func displayName(for identifier: String) -> String {
        let first = firstSynonym(of: identifier)
        let zh = translate(identifier)
        return zh == first ? first : "\(zh)（\(first)）"
    }
